#!/usr/bin/env python3
"""Check n = 2^H*q^k*u*v for all k>=1 and all distinct odd primes q,u,v.

The four-prime reduction isolates u<v and bounds the remaining prime positions.
The exponent is never bounded: modular residues and a saturated comparison
with 2^H are generated by walking until a state repeats. The four-prime proof gives the local degree, norm, trace, and Gram constraints used below.
An empty output list excludes all ordinary minimal roots of the indicated
form. Any surviving class is inconclusive, since these are necessary tests.
"""
from argparse import ArgumentParser
from dataclasses import dataclass
from functools import lru_cache
from math import isqrt, lcm


TRACE_MODULUS = 81


def primes(first, last):
    return (n for n in range(first, last+1)
            if n >= 2 and all(n % i for i in range(2, isqrt(n)+1)))


@lru_cache(None)
def power_states(q, modulus, cap=4):
    """Pairs (q^i mod modulus, min(q^i,cap)) for all positive i."""
    state = (q % modulus, min(q, cap))
    seen = set()
    while state not in seen:
        seen.add(state)
        residue, capped = state
        state = ((q*residue) % modulus, min(q*capped, cap))
    return tuple(sorted(seen))


def centered(n, t):
    r = n % t
    return r if 2*r < t else r-t


@dataclass(frozen=True)
class Case:
    q: int
    u: int
    v: int
    power: int  # q^k modulo u*v
    sign: int
    ju: int
    jv: int
    height: int = 2

    @property
    def dyadic_power(self):
        return 2**self.height

    def dyadic_factors(self):
        return (2**i for i in range(1,self.height+1))

    def ends(self):
        return ((self.u, self.v, self.ju), (self.v, self.u, self.jv))


def configurations(height=2):
    dyadic_power = 2**height
    for u in primes(5, 2*dyadic_power):
        for v in primes(u+1, dyadic_power*u+1):
            qmax = 2*u if v > 2*u else v*u+1
            for q in primes(3,qmax):
                if q in (u,v):
                    continue
                for power in sorted({r for r,_ in power_states(q,u*v,dyadic_power)}):
                    g = dyadic_power * power
                    for sign in (-1,1):
                        ju = (-sign*pow(g*v, -1, u)) % u
                        jv = (-sign*pow(g*u, -1, v)) % v
                        if ((u-1)%ju and (u+1)%ju) or ((v-1)%jv and (v+1)%jv):
                            continue
                        opposite_rank = max(2, (u+1)//ju - 1)
                        if v > dyadic_power*opposite_rank+1 or q > v*opposite_rank+1:
                            continue
                        if v*ju+u*jv < u*v:
                            yield Case(q,u,v,power,sign,ju,jv,height)


def orbit_bound(t, g):
    if t <= 2*g:
        return 1
    return (t-1) // max(d for d in range(1, g+1) if (t-1)%d == 0)


def local_coordinate(h, t, j, sign):
    """Return the signed coordinate and whether an unramified row is allowed."""
    r = centered(h,t)
    a = centered(-sign*j*h,t)
    if j*abs(r)*(t-abs(r)) >= t*t:
        return None,False
    unramified = a == -sign*j*r and (t-1)*j*r*r < t*t
    if j == 1 and not unramified:
        return None,False
    return a,unramified


def cheapest_axis(case,t,w,j,base,capacity):
    """Minimum cost of a nonempty axis satisfying its necessary trace residue."""
    q = case.q
    if base == 2:
        powers, other = case.dyadic_factors(), q
    else:
        powers = (r for r,_ in power_states(q,2*t,case.dyadic_power))
        other = 2
    groups = {}
    for y in powers:
        h = y*w
        a,unram = local_coordinate(h,t,j,case.sign)
        if a is None:
            continue
        cost, residue = a*a, (a*h) % other
        lower = max(1 if unram else 2, orbit_bound(t,w), orbit_bound(other,w))
        key = (cost,residue)
        groups[key] = min(lower, groups.get(key,lower))

    # Multiple degree types with identical (cost,residue) may be aggregated:
    # zero copies or any count >= the smallest forced multiplicity is sound.
    best = {}
    for (cost,residue), lower in groups.items():
        updated = best.copy()
        for current, used in [(0,0), *best.items()]:
            for m in range(lower, 1+(capacity-used)//cost):
                target = (current + m*residue) % other
                price = used + m*cost
                if price < updated.get(target,capacity+1):
                    updated[target] = price
        best = updated
    return best.get((case.sign*j) % other)


def common_budgets(case):
    budgets = []
    for t,w,j in case.ends():
        cap = j*(t+1-j)-1  # one further full degree beyond the active baseline
        for base in (2,case.q):
            price = cheapest_axis(case,t,w,j,base,cap)
            if price is None:
                return None
            cap -= price
        budgets.append(cap)
    return tuple(budgets)


def has_common_gram(case, budgets):
    """Try the two-endpoint Gram sum on all possible common degree signatures."""
    q,u,v = case.q,case.u,case.v
    groups = {}
    for power, capped in power_states(q,u*v,case.dyadic_power):
        for two_part in case.dyadic_factors():
            g = min(two_part,capped)
            h = two_part*power
            a,fu = local_coordinate(h,u,case.ju,case.sign)
            b,fv = local_coordinate(h,v,case.jv,case.sign)
            if a is None or b is None:
                continue
            free_ends = int(fu and u <= 2*g) + int(fv and v <= 2*g)
            if free_ends == 0:
                continue
            lower = max(3-free_ends, orbit_bound(u,g), orbit_bound(v,g))
            key = (a,b)
            groups[key] = min(lower, groups.get(key,lower))

    choices = list(groups.items())
    # An explicit stack also works when a larger height has more signatures
    # than Python's call-stack limit.
    pending = [(0,*budgets,-case.ju*case.jv)]
    seen = set()
    while pending:
        state = pending.pop()
        if state in seen:
            continue
        seen.add(state)
        i, cu, cv, remaining = state
        if remaining == 0:
            return True
        if i == len(choices):
            continue
        (a,b), minimum = choices[i]
        maximum = min(cu//(a*a), cv//(b*b))
        for m in range(minimum,maximum+1):
            pending.append((i+1,cu-m*a*a,cv-m*b*b,remaining-m*a*b))
        pending.append((i+1,cu,cv,remaining))
    return False


def has_residual_trace(case,t,w,j,modulus):
    """Exact finite norm, with the residual degree trace projected modulo modulus."""
    period = lcm(case.u*case.v,modulus)
    powers = power_states(case.q,period,case.dyadic_power)
    root_residues = {r % modulus for r,_ in powers
                     if r % (case.u*case.v) == case.power}
    # Flags require at least one dyadic axis, one q-axis, and one common row.
    types = set()
    factors = [(1,1,False), *((r,capped,True) for r,capped in powers)]
    for w_part in (False,True):
        for two_part in (1,*case.dyadic_factors()):
            for q_part, capped, positive in factors:
                if not w_part and (two_part == 1 or not positive):
                    continue  # forbidden unit or prime power
                if w_part and two_part == 1 and not positive:
                    continue  # the prime w alone
                if not w_part and j == 1 and t > 2*min(two_part,capped):
                    continue  # all inactive rows unramified, use both axis gcd bounds
                h = two_part*q_part*(w if w_part else 1)
                a,_ = local_coordinate(h,t,j,case.sign)
                if a is None:
                    continue
                flag = (int(w_part and not positive)
                        | (2 if w_part and two_part == 1 else 0)
                        | (4 if not w_part else 0))
                types.add((a*a, h*a % modulus, flag))

    # Bounded by squared cost. Further full rows are permitted among 'types'.
    capacity = j*(t+1-j)-1
    levels = [set() for _ in range(capacity+1)]
    levels[0].add((0,0))
    for used in range(capacity):
        for cost,residue,flag in types:
            if used+cost <= capacity:
                levels[used+cost].update(((s+residue)%modulus, f|flag)
                                         for s,f in levels[used])
    for root in root_residues:
        target = ((j-1)*case.dyadic_power*root*w+case.sign*j) % modulus
        if (target,7) in levels[capacity]:
            return True
    return False


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--dyadic-height", type=int, default=2, metavar="H",
                        help="fix H>=2 and let the odd exponent range over all k")
    args = parser.parse_args()
    if args.dyadic_height < 2:
        parser.error("--dyadic-height must be at least 2")
    pairs = []
    axes = 0
    count = 0
    for case in configurations(args.dyadic_height):
        count += 1
        budgets = common_budgets(case)
        if budgets is not None:
            axes += 1
            if has_common_gram(case,budgets):
                pairs.append(case)
    unresolved = [case for case in pairs
                  if all(has_residual_trace(case,t,w,j,TRACE_MODULUS)
                         for t,w,j in case.ends())]
    print(f"Vacuum residue cases {count}, axes {axes}, paired Gram {len(pairs)}, "
          f"after residual trace modulo {TRACE_MODULUS}: {len(unresolved)}.")
    if unresolved:
        print("Surviving classes are inconclusive. These tests are necessary conditions.")
    for case in unresolved:
        print("Unresolved residue class:",case)
    return 2 if unresolved else 0


if __name__ == "__main__":
    raise SystemExit(main())
