#!/usr/bin/env python3
"""Exact normalized rank-three commutator catalogue at formal codegree six.

This producer has no dependencies beyond the Python standard library.  The
normalization is T=[I_3|A], with oriented, nondecreasing extra columns.  Column
signs are restored before duality and traces are tested.  Every output state
contains its actual integral frame, involution and trace vector, rather than
only a claimed row pattern.  Counts are regression checks, not input data.
"""
from collections import Counter
from fractions import Fraction
from functools import lru_cache
from itertools import combinations, product
from pathlib import Path
import json

HERE = Path(__file__).resolve().parent
I3 = ((1,0,0),(0,1,0),(0,0,1))

def det3(a,b,c):
    return (a[0]*(b[1]*c[2]-b[2]*c[1])
            -a[1]*(b[0]*c[2]-b[2]*c[0])
            +a[2]*(b[0]*c[1]-b[1]*c[0]))

def dot(a,b):
    return sum(x*y for x,y in zip(a,b))

def matrix_product(a,b):
    return tuple(tuple(dot(r,c) for c in zip(*b)) for r in a)

def gram(columns):
    h=tuple(tuple(sum(v[i]*v[j] for v in columns) for j in range(3)) for i in range(3))
    adj=tuple(tuple(((-1)**(i+j))*(
        h[[a for a in range(3) if a!=j][0]][[b for b in range(3) if b!=i][0]]*
        h[[a for a in range(3) if a!=j][1]][[b for b in range(3) if b!=i][1]]-
        h[[a for a in range(3) if a!=j][0]][[b for b in range(3) if b!=i][1]]*
        h[[a for a in range(3) if a!=j][1]][[b for b in range(3) if b!=i][0]])
        for j in range(3)) for i in range(3))
    return tuple(tuple(dot(x,tuple(dot(r,y) for r in adj)) for y in columns) for x in columns)

@lru_cache(None)
def oriented_columns():
    return tuple(sorted(v for v in product(range(-3,4),repeat=3)
                        if 0<dot(v,v)<=11 and next(a for a in v if a)>0))

def column_multisets():
    """All multisets of at most four oriented vectors with total norm <=11."""
    vectors=oriented_columns()
    def visit(prefix,start,left):
        yield prefix
        if len(prefix)==4:return
        for k in range(start,len(vectors)):
            v=vectors[k];n=dot(v,v)
            if n<=left:yield from visit(prefix+(v,),k,left-n)
    yield from visit((),0,11)

def normalized_frames():
    for extra in column_multisets():
        columns=I3+extra;n=len(columns)
        nonzero=[abc for abc in combinations(range(n),3)
                 if det3(*(columns[i] for i in abc))]
        mass=sum(det3(*(columns[i] for i in abc))**2 for abc in nonzero)
        if mass!=12:continue
        if any(all(i in abc for abc in nonzero) for i in range(n)):continue
        yield columns

@lru_cache(None)
def involutions(n):
    def visit(left,values):
        if not left:
            yield tuple(values);return
        i,*rest=left;values[i]=i
        yield from visit(rest,values)
        for j in rest:
            values[i]=j;values[j]=i
            yield from visit([k for k in rest if k!=j],values)
    return tuple(visit(list(range(n)),[None]*n))

def dualities(g):
    n=len(g)
    for d in involutions(n):
        if sum(g[i][d[i]] for i in range(n))!=12:continue
        if any(g[d[i]][d[j]]!=g[i][j] for i in range(n) for j in range(n)):continue
        yield d

def trace_vectors(columns,g,d):
    n=len(columns)
    for tail in product(range(-2,3),repeat=n-3):
        head=tuple(-sum(columns[j+3][i]*tail[j] for j in range(n-3)) for i in range(3))
        if any(abs(x)>2 for x in head):continue
        s=head+tail
        if any(s[d[i]]!=s[i] for i in range(n)):continue
        if 8-dot(s,s) not in (0,4,8):continue
        if any((s[i]*s[i]-g[i][d[i]])%4 for i in range(n)):continue
        if any((s[i]*s[i]+g[i][i])%2 or (s[i]*s[i]+g[i][i])//2>=6 for i in range(n)):continue
        yield s

def integral_state(g,s):
    modulus=4 if all(x%2==0 for x in s) else 2
    return all((g[i][j]+s[i]*s[j])%modulus==0
               for i in range(len(g)) for j in range(len(g)))

def nullspace_one(vectors):
    """Return a 1-dimensional rational null vector, otherwise None."""
    if not vectors:return None
    a=[list(map(Fraction,r)) for r in zip(*vectors)]
    m=len(a);n=len(vectors);piv=[];row=0
    for col in range(n):
        k=next((k for k in range(row,m) if a[k][col]),None)
        if k is None:continue
        a[row],a[k]=a[k],a[row]
        q=a[row][col];a[row]=[x/q for x in a[row]]
        for k in range(m):
            if k!=row:
                q=a[k][col];a[k]=[x-q*y for x,y in zip(a[k],a[row])]
        piv.append(col);row+=1
        if row==m:break
    free=[k for k in range(n) if k not in piv]
    if len(free)!=1:return None
    v=[Fraction(0)]*n;v[free[0]]=Fraction(1)
    for j,p in enumerate(piv):v[p]=-a[j][free[0]]
    return tuple(v)

def positive_kernel(columns,d):
    """Exact strict positive cone test, by positive circuits of size <=4.

    A nonnegative kernel is generated by its support-minimal rays.  In rank
    at most three each such ray has support at most four.  There exists a
    strictly positive kernel iff these supports cover every coordinate.
    Dual coordinates have first been identified, so their dimensions agree.
    """
    groups=[(i,) if i==d[i] else (i,d[i]) for i in range(len(d)) if i<=d[i]]
    v=[tuple(sum(columns[i][j] for i in group) for j in range(3)) for group in groups]
    covered=set();witness=[Fraction(0)]*len(v)
    for k in range(1,min(4,len(v))+1):
        for ids in combinations(range(len(v)),k):
            q=nullspace_one([v[i] for i in ids])
            if q is None or not(all(x>0 for x in q) or all(x<0 for x in q)):continue
            if q[0]<0:q=tuple(-x for x in q)
            covered.update(ids)
            for i,x in zip(ids,q):witness[i]+=x
    if len(covered)!=len(v):return None
    output=[None]*len(d)
    for group,x in zip(groups,witness):
        for i in group:output[i]=x
    assert all(x>0 for x in output)
    assert all(sum(v[i]*output[j] for j,v in enumerate(columns))==0 for i in range(3))
    return tuple(output)

def row_signature(g,d,s,signed=True):
    rows=[]
    for i in range(len(d)):
        if i>d[i]:continue
        j=d[i]
        trace=s[i] if signed else abs(s[i])
        if i==j:rows.append((True,g[i][i],0,trace))
        else:rows.append((False,(g[i][i]+g[i][j])//2,(g[i][i]-g[i][j])//2,trace))
    return tuple(sorted(rows))

PATTERNS={
    'A':((False,0,3,1),(False,0,3,1),(True,8,0,0),(True,8,0,0),(True,8,0,0)),
    'B':((False,2,6,0),(True,5,0,1),(True,5,0,1),(True,5,0,1),(True,5,0,1)),
    'D':((False,3,6,1),(True,5,0,1),(True,5,0,1),(True,8,0,0)),
    'E':((False,4,3,1),(False,4,3,1),(True,4,0,0),(True,4,0,2)),
    'F':((False,3,2,1),(False,3,2,1),(False,6,2,0)),
}

def family(g,d,s):
    r=row_signature(g,d,s,False)
    return next((name for name,rows in PATTERNS.items() if r==rows),None)

def produce():
    counts=Counter();states=[];signatures=set();positive_signatures=set()
    frames=list(normalized_frames())
    counts['oriented_columns']=len(oriented_columns())
    counts['normalized_inputs']=sum(1 for _ in column_multisets())
    counts['norm12_frames']=len(frames)
    for frame_id,base in enumerate(frames):
        for signs in product((-1,1),repeat=len(base)-3):
            columns=I3+tuple(tuple(x*s for x in v) for v,s in zip(base[3:],signs))
            g=gram(columns)
            assert matrix_product(g,g)==tuple(tuple(12*x for x in r) for r in g)
            for d in dualities(g):
                for s in trace_vectors(columns,g,d):
                    counts['trace_states']+=1
                    if not integral_state(g,s):continue
                    counts['integral_states']+=1
                    name=family(g,d,s)
                    assert name is not None,(g,d,s,row_signature(g,d,s,False))
                    counts['integral_'+name]+=1
                    signature=row_signature(g,d,s)
                    signatures.add(signature)
                    witness=positive_kernel(columns,d)
                    rec={'frame':frame_id,'columns':columns,'duality':d,'traces':s,
                         'gram':g,'family':name,'positive':witness is not None,
                         'positive_witness':None if witness is None else [str(x) for x in witness]}
                    states.append(rec)
                    if witness is not None:
                        counts['positive_states']+=1;counts['positive_'+name]+=1
                        positive_signatures.add(signature)
    counts['integral_signed_signatures']=len(signatures)
    counts['positive_signed_signatures']=len(positive_signatures)
    return {'scope':'all normalized coloop-free integral decomposable norm-12 three-forms, with orthogonal duality and integral traces',
            'counts':dict(sorted(counts.items())),
            'frames':frames,'states':states,
            'positive_signed_signatures':sorted(positive_signatures)}

def profiles(b,delta,classes,rank=16):
    """Necessary unsigned matrix row-count profiles, excluding the unit.

    Keys are (self_dual, abs(trace), trace(AA*), determinant).  A false key
    counts *duality pairs*, not individual labels.  Thus total rank is
    1 + sum(count*(1 if sd else 2)).  The sign constraints and exact dimension
    couplings are stronger than this intentionally relaxed row interface.
    """
    if delta not in (3,6):return
    forms={tuple(x) for x in classes}
    for name in ('A','B','D','E'):
        if delta!=(6 if name in ('B','D') else 3):continue
        if (() if name=='E' else (2,3)) not in forms:continue
        counter=Counter()
        for sd,j,k,s in PATTERNS[name]:
            counter[(sd,s,(s*s+j+k)//2,(s*s-j+k)//4)]+=1
        if name!='E':counter[(True,2,2,1)]+=1
        pairs=sum(v for (sd,*_),v in counter.items() if not sd)
        singles=sum(v for (sd,*_),v in counter.items() if sd)
        missing_pairs=b-pairs;missing_singles=rank-1-2*b-singles
        if min(missing_pairs,missing_singles)<0:continue
        if missing_pairs:counter[(False,0,0,0)]+=missing_pairs
        if missing_singles:counter[(True,0,0,0)]+=missing_singles
        yield counter

if __name__=='__main__':
    data=produce()
    target=HERE/'orthogonal_six_catalogue.json'
    target.write_text(json.dumps(data,separators=(',',':'))+'\n')
    print(json.dumps(data['counts'],indent=2,sort_keys=True))
